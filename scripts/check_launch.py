"""Launch gate for the CropCare website and app copy. Exits non-zero if any rule fails.

  python scripts/check_launch.py

Rules (from the project owner):
  - a custom domain is connected (site/CNAME)
  - every page has a favicon and links to the privacy policy
  - no "made with AI" style tags, no placeholders left
  - no em dashes, no emoji, no gradients, no pill-shaped buttons,
    no scroll or cursor animation, no third-party scripts or fonts
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
APP_COPY = [ROOT / "app/src/i18n.ts", ROOT / "app/assets/advice.json"]

EMOJI = re.compile(
    "[\U0001F000-\U0001FAFF\U00002600-\U000027BF\U0001F1E6-\U0001F1FF\U00002B00-\U00002BFF\uFE0F]"
)
DASHES = re.compile("[\u2014\u2013]")  # em dash, en dash
TAGS = re.compile(r"made with|built with|powered by|generated by|created with|\bAI[- ]generated", re.I)
PLACEHOLDER = re.compile(r"LAUNCH-TODO|lorem ipsum|your-domain|example\.com", re.I)

failures: list[str] = []


def fail(msg: str) -> None:
    failures.append(msg)


def check_domain() -> None:
    cname = SITE / "CNAME"
    if not cname.is_file():
        fail("site/CNAME missing: connect a custom domain and put it in site/CNAME")
        return
    domain = cname.read_text(encoding="utf-8").strip()
    if not re.fullmatch(r"(?=.{4,253}$)([a-z0-9-]+\.)+[a-z]{2,}", domain, re.I) or PLACEHOLDER.search(domain):
        fail(f"site/CNAME does not hold a real domain: {domain!r}")


def check_pages() -> None:
    pages = sorted(SITE.glob("*.html"))
    if not (SITE / "privacy.html").is_file():
        fail("site/privacy.html missing")
    for page in pages:
        html = page.read_text(encoding="utf-8")
        name = page.name
        icons = re.findall(r'<link[^>]+rel="(?:icon|shortcut icon)"[^>]+href="([^"]+)"', html)
        if not icons:
            fail(f"{name}: no favicon link")
        for href in icons:
            if not (SITE / href.lstrip("/")).is_file():
                fail(f"{name}: favicon {href} does not exist")
        if 'href="privacy.html"' not in html and 'href="/privacy.html"' not in html:
            fail(f"{name}: no link to the privacy policy")
        if re.search(r"<script\b", html, re.I):
            fail(f"{name}: contains a script tag")
        if re.search(r"fonts\.googleapis|fonts\.gstatic|use\.typekit", html):
            fail(f"{name}: loads a third-party font")
        if "data-launch-required" in html:
            fail(f"{name}: has a data-launch-required placeholder to fill in")


def check_text(path: Path) -> None:
    text = path.read_text(encoding="utf-8")
    rel = path.relative_to(ROOT).as_posix()
    for i, line in enumerate(text.splitlines(), 1):
        if DASHES.search(line):
            fail(f"{rel}:{i}: em or en dash")
        if EMOJI.search(line):
            fail(f"{rel}:{i}: emoji")
        if path.suffix == ".html" and TAGS.search(re.sub(r"<[^>]+>", " ", line)):
            fail(f"{rel}:{i}: generator tag ('made with', 'powered by', ...)")
        if PLACEHOLDER.search(line):
            fail(f"{rel}:{i}: placeholder text left in")


def check_css() -> None:
    for css in SITE.glob("*.css"):
        text = css.read_text(encoding="utf-8")
        rel = css.relative_to(ROOT).as_posix()
        if "gradient(" in text:
            fail(f"{rel}: uses a gradient")
        for m in re.finditer(r"border-radius:\s*([^;]+);", text):
            value = m.group(1)
            if "%" in value or "var(" not in value and any(float(n) >= 16 for n in re.findall(r"(\d+(?:\.\d+)?)px", value)):
                fail(f"{rel}: border-radius {value.strip()} would make pill or round buttons")
        if re.search(r"@keyframes|animation\s*:|scroll-behavior\s*:\s*smooth|scroll-timeline|view-timeline", text):
            fail(f"{rel}: uses animation")
        if re.search(r"cursor\s*:\s*url\(", text):
            fail(f"{rel}: custom cursor")


def main() -> int:
    check_domain()
    check_pages()
    for path in [*SITE.glob("*.html"), *SITE.glob("*.css"), *APP_COPY]:
        check_text(path)
    check_css()
    if failures:
        print(f"NOT READY TO LAUNCH: {len(failures)} problem(s)")
        for f in failures:
            print(f"  - {f}")
        return 1
    print("Launch checks passed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
