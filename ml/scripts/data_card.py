"""Write ml/data_card.md: image counts per class, source and split."""

import argparse
from collections import Counter
from pathlib import Path

import _bootstrap  # noqa: F401
from cropcare import manifest
from cropcare.classes import ClassMap

COLUMNS = [
    ("plantvillage", "train"), ("plantvillage", "val"), ("plantvillage", "test"),
    ("plantdoc", "train"), ("plantdoc", "val"), ("plantdoc", "test"),
    ("plantvillage_bgswap", "train"), ("field", "test"),
]


def render(rows: list[manifest.Row], labels: tuple[str, ...]) -> str:
    counts = Counter((r.label, r.source, r.split) for r in rows)
    header = "| Class | " + " | ".join(f"{s} {sp}" for s, sp in COLUMNS) + " |"
    lines = [
        "# Data card",
        "",
        "Generated by `scripts/data_card.py` from `data/manifest.csv`. Do not edit by hand.",
        "",
        header,
        "|" + "---|" * (len(COLUMNS) + 1),
    ]
    for label in labels:
        lines.append(f"| {label} | " + " | ".join(str(counts[(label, s, sp)]) for s, sp in COLUMNS) + " |")
    totals = [sum(counts[(label, s, sp)] for label in labels) for s, sp in COLUMNS]
    lines.append("| **Total** | " + " | ".join(str(t) for t in totals) + " |")
    lines += [
        "",
        "PlantDoc has no healthy potato or healthy maize images (docs/DECISIONS.md ADR-002).",
        "Field photos are test only.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data-dir", type=Path, default=Path("../data"))
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parent.parent / "data_card.md")
    args = ap.parse_args()
    rows = manifest.read(args.data_dir / "manifest.csv")
    args.out.write_text(render(rows, ClassMap.load().labels), encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
